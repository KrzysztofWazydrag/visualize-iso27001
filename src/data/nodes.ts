function node(
  id: string,
  title: string,
  type: NodeType,
  summary: string,
  purpose: string,
  owner: string,
  clauseRefs: string[],
  evidence: string[],
  question: string,
  mistake: string,
  controlRefs: string[] = [],
): LearningNode {
  return {
    id,
    title,
    type,
    shortDescription: summary,
    description: summary,
    purpose,
    typicalOwner: owner,
    clauseRefs,
    controlRefs,
    evidenceExamples: evidence,
    auditQuestions: [question],
    misconceptions: [mistake],
  };
}
